// 밴드 참불 명단 글 → 참석자 이름.
//
// 밴드에서 복사해 오는 글은 모양이 일정하지 않다. 출석체크 화면을 통째로 긁으면
// "참석 12" 같은 머리줄 아래 이름이 한 줄씩 오고, 게시글 댓글을 긁으면
// "1. 홍길동 참" · "김철수(92) 참석!" 처럼 번호 · 나이 · 말이 섞여 온다.
// 그래서 모양을 맞히려 하지 않고 두 가지만 한다.
//
//   1) 로스터 이름을 글 속에서 찾는다. 앞뒤가 한글이 아닐 때만 이름으로 본다
//      ("김산" 이 "김산책" 안에서 잡히지 않게).
//   2) 로스터에 없는 2~4글자 한글 낱말은 "게스트일지 모르는 이름" 으로만 내놓는다.
//      자동으로 넣지 않고 사람이 고른다 — "참석" "오늘" 같은 말이 섞여 들어오기 때문이다.
//
// "불참" · "미정" · "미응답" 이 적힌 머리줄 아래 이름은 참석으로 치지 않는다.
// 다시 "참석" 머리줄이 나오면 그 아래부터는 참석이다. 한 줄 안에 이름과 함께
// "불참" 이 적혀 있으면("홍길동 불참") 그 줄 사람도 빼 둔다.

const 한글 = /[가-힣]/;
const 빼는말 = /불참|미정|미응답|못\s*가|못\s*감|빠질게|빠집니다|안\s*가/;
const 참석말 = /참석|^\s*참\s*$|^\s*참\s*[:(\d]/;

// 이름 후보로 나와도 이름이 아닌 흔한 말. 게스트 후보에서만 쓴다.
const 이름아닌말 = new Set([
  "참석", "불참", "미정", "미응답", "참가", "출석", "출석체크", "체크", "명단", "투표", "댓글",
  "게스트", "오늘", "내일", "이번", "이번주", "다음", "다음주", "주말", "일요일", "토요일", "수요일",
  "자체전", "농구", "경기", "운동", "시간", "장소", "입니다", "합니다", "해요", "할게요", "갑니다",
  "가요", "늦참", "지각", "조금", "늦게", "먼저", "혹시", "감사", "감사합니다", "화이팅", "파이팅",
  "모두", "전원", "다시", "인원", "총원", "현재", "기준", "마감", "신청", "완료", "확인", "공지", "사항",
  "선착순", "대기", "명", "님", "회원", "멤버", "리더", "매니저", "혼", "스피릿", "신당초",
  "신당초등학교", "후문", "주차", "샤워",
]);

function 이름자리(글, 이름) {
  const 자리들 = [];
  let i = 글.indexOf(이름);
  while (i !== -1) {
    const 앞 = 글[i - 1] || "";
    const 뒤 = 글[i + 이름.length] || "";
    // "님" 은 이름 뒤에 흔히 붙는다("홍길동님"). 그 밖의 한글이 붙어 있으면 더 긴 낱말의 일부다.
    if (!한글.test(앞) && (!한글.test(뒤) || 뒤 === "님")) 자리들.push(i);
    i = 글.indexOf(이름, i + 1);
  }
  return 자리들;
}

/**
 * @param {string} 글      붙여 넣은 글
 * @param {string[]} 이름들  로스터(와 이미 있는 게스트) 이름
 * @returns {{ 찾음: string[], 뺌: string[], 모름: string[] }}
 *   찾음: 참석으로 읽힌 로스터 이름(글에 나온 차례) · 뺌: 불참 쪽에 적힌 로스터 이름
 *   모름: 로스터에 없는 이름 같은 낱말(게스트 후보)
 */
export function 참석명단읽기(글, 이름들) {
  const 찾음 = [], 뺌 = [], 모름 = [];
  const 긴이름먼저 = [...new Set(이름들)].sort((a, b) => b.length - a.length);
  let 빼는구역 = false;
  for (const 줄원본 of String(글 || "").split(/\r?\n/)) {
    const 줄 = 줄원본.trim();
    if (!줄) continue;
    // 이 줄에 로스터 이름이 있는지부터 — 머리줄인지 이름 줄인지 가르는 데 쓴다.
    const 자리붙은이름 = [];
    let 남은줄 = 줄;
    for (const n of 긴이름먼저) {
      const 자리 = 이름자리(남은줄, n);
      if (자리.length) {
        자리붙은이름.push([자리[0], n]);
        // 찾은 이름은 같은 길이의 빈칸으로 지운다 — "조우진" 을 찾은 뒤 그 안의 "우진" 이
        // 다시 잡히지 않게. 길이를 지켜야 다른 이름의 자리(글 속 차례)가 안 밀린다.
        남은줄 = 남은줄.split(n).join(" ".repeat(n.length));
      }
    }
    // 글에 나온 차례대로.
    const 줄이름 = 자리붙은이름.sort((a, b) => a[0] - b[0]).map(([, n]) => n);
    const 빼는줄 = 빼는말.test(줄);
    if (!줄이름.length) {
      // 이름 없는 줄은 머리줄일 수 있다.
      if (빼는줄) 빼는구역 = true;
      else if (참석말.test(줄)) 빼는구역 = false;
    }
    const 빼기 = 빼는구역 || (줄이름.length > 0 && 빼는줄);
    for (const n of 줄이름) (빼기 ? 뺌 : 찾음).push(n);
    if (빼기) continue;
    // 로스터에 없는 이름 같은 낱말: 한글 2~4글자 덩어리. 뒤에 붙은 "님" 은 뗀다.
    // 한글 낱말이 넷 이상인 줄은 이름 줄이 아니라 문장이다("오늘 게스트 한명 데려가요").
    const 낱말들 = [...남은줄.matchAll(/[가-힣]+/g)];
    if (낱말들.length > 3) continue;
    for (const m of 남은줄.matchAll(/[가-힣]{2,5}/g)) {
      const w = m[0].replace(/님$/, "");
      if (w.length < 2 || w.length > 4 || 이름아닌말.has(w) || /참석|불참|출석/.test(w)) continue;
      // "데려가요" "갑니다" 같은 말끝, "한명" "두명" 같은 인원 말은 이름이 아니다.
      if (/(요|니다|해요|죠)$/.test(w) || /^[한두세네]\s*명$/.test(w)) continue;
      모름.push(w);
    }
  }
  const 한번씩 = (a) => [...new Set(a)];
  const 찾은것 = 한번씩(찾음);
  return {
    찾음: 찾은것,
    // 참석에도 불참에도 적힌 이름은(댓글로 번복 등) 참석으로 둔다 — 빼는 쪽이 더 위험하다.
    뺌: 한번씩(뺌).filter((n) => !찾은것.includes(n)),
    모름: 한번씩(모름).filter((n) => !이름들.includes(n)),
  };
}
